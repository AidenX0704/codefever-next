// glyphWidth 是点阵字体的字宽（像素）。
const glyphWidth = 5

// glyphHeight 是点阵字体的字高（像素）。
const glyphHeight = 7

// drawText 用内置点阵字体把文本画到画布上。
//
// x、y 是左上角坐标；scale 是放大倍数（1 表示原始点阵大小）。
// 画不出的字符按空格处理。
func drawText(img *image.RGBA, text string, x, y, scale int, col color.RGBA) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range text {
		if r < 0x20 || r > 0x7E {
			r = ' '
		}
		glyph := font5x7[r-0x20]
		for colIdx := 0; colIdx < glyphWidth; colIdx++ {
			bits := glyph[colIdx]
			for row := 0; row < glyphHeight; row++ {
				if bits&(1<<uint(row)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						img.Set(cx+colIdx*scale+dx, y+row*scale+dy, col)
					}
				}
			}
		}
		cx += glyphWidth * scale
	}
}

// encodePNG 把画布编码成 PNG 字节。
func encodePNG(img image.Image) ([]byte, error) {
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// newCanvas 创建一张纯色画布。
func newCanvas(w, h int, bg color.RGBA) *image.RGBA {
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.SetRGBA(x, y, bg)
		}
	}
	return img
}

// identicon 按输入串生成一枚对称的识别图（5x5 网格，左右镜像）。
//
// 用于注册头像：PHP 侧用 MDAvtars 扩展生成，这里用 md5 派生的颜色与图案，
// 同样是"同一个输入总是得到同一张图"，但像素与 PHP 不同。
func identicon(input string, size int) *image.RGBA {
	sum := md5.Sum([]byte(input))
	bg := color.RGBA{R: 0xF0, G: 0xF0, B: 0xF0, A: 0xFF}
	fg := color.RGBA{R: sum[0], G: sum[1], B: sum[2], A: 0xFF}
	img := newCanvas(size, size, bg)

	cell := size / 5
	if cell < 1 {
		cell = 1
	}
	for row := 0; row < 5; row++ {
		for col := 0; col < 3; col++ {
			bit := row*3 + col
			if sum[3+bit/8]&(1<<uint(bit%8)) == 0 {
				continue
			}
			for _, c := range []int{col, 4 - col} {
				fillRect(img, c*cell, row*cell, cell, cell, fg)
			}
		}
	}
	return img
}

// fillRect 用实心矩形填充画布的一块区域。
func fillRect(img *image.RGBA, x0, y0, w, h int, col color.RGBA) {
	for y := y0; y < y0+h; y++ {
		for x := x0; x < x0+w; x++ {
			img.SetRGBA(x, y, col)
		}
	}
}

// randColor 生成一个随机的深色（用于验证码字符）。
func randColor(rnd *rand.Rand) color.RGBA {
	return color.RGBA{
		R: uint8(0x20 + rnd.Intn(0x60)),
		G: uint8(0x40 + rnd.Intn(0x60)),
		B: uint8(0xA0 + rnd.Intn(0x50)),
		A: 0xFF,
	}
}
