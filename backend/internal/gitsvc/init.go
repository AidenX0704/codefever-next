// GitignoreTemplate 按名称读取内置 .gitignore 模板（大小写不敏感）。
func GitignoreTemplate(name string) (string, bool) {
	key := strings.ToLower(strings.TrimSpace(name))
	if key == "" {
		return "", false
	}
	tpl, ok := gitignoreTemplates[key]
	return tpl, ok
}

// InitBareWithFiles 初始化裸仓库，并按需设置默认分支 HEAD、创建初始提交（README / .gitignore）。
//
// 当 opts 既不初始化 README 也不选 .gitignore 时，仅执行裸仓初始化并把 HEAD 指向
// DefaultBranch（若指定），不产生任何提交。
func (s *Service) InitBareWithFiles(ctx context.Context, repoPath string, opts InitOptions) error {
	if err := s.InitBare(ctx, repoPath); err != nil {
		return err
	}

	branch := strings.TrimPrefix(strings.TrimSpace(opts.DefaultBranch), "refs/heads/")
	if branch == "" {
		branch = "main"
	}
	if err := rejectOptionLike(branch); err != nil {
		return err
	}

	gitignoreContent := ""
	if strings.TrimSpace(opts.Gitignore) != "" {
		tpl, ok := GitignoreTemplate(opts.Gitignore)
		if !ok {
			return fmt.Errorf("不支持的 .gitignore 模板: %s", opts.Gitignore)
		}
		gitignoreContent = tpl
	}

	// 即使不生成初始文件，也把空裸仓的 HEAD 指向用户指定的默认分支，
	// 避免后续首次 push main 时 HEAD 仍停留在 master。
	if !opts.InitReadme && gitignoreContent == "" {
		if _, err := s.run(ctx, repoPath, "symbolic-ref", "HEAD", "refs/heads/"+branch); err != nil {
			return err
		}
		return chmodRecursive(repoPath)
	}

	workspace, err := os.MkdirTemp("", "codefever-init-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(workspace)

	if _, err := s.run(ctx, workspace, "init"); err != nil {
		return err
	}
	if _, err := s.run(ctx, workspace, "checkout", "-b", branch); err != nil {
		return err
	}

	if opts.InitReadme {
		title := strings.TrimSpace(opts.RepoDisplayName)
		if title == "" {
			title = "Repository"
		}
		var sb strings.Builder
		sb.WriteString("# ")
		sb.WriteString(title)
		sb.WriteString("\n")
		if desc := strings.TrimSpace(opts.RepoDescription); desc != "" {
			sb.WriteString("\n")
			sb.WriteString(desc)
			sb.WriteString("\n")
		}
		if err := os.WriteFile(filepath.Join(workspace, "README.md"), []byte(sb.String()), 0o644); err != nil {
			return err
		}
	}

	if gitignoreContent != "" {
		if err := os.WriteFile(filepath.Join(workspace, ".gitignore"), []byte(gitignoreContent), 0o644); err != nil {
			return err
		}
	}

	authorName := strings.TrimSpace(opts.AuthorName)
	authorEmail := strings.TrimSpace(opts.AuthorEmail)
	if authorName == "" {
		authorName = "codefever"
	}
	if authorEmail == "" {
		authorEmail = "noreply@codefever.local"
	}
	env := committerEnv(authorName, authorEmail)

	if _, err := s.runWithEnv(ctx, workspace, env, "add", "-A"); err != nil {
		return err
	}
	if _, err := s.runWithEnv(ctx, workspace, env, "commit", "-m", "Initial commit"); err != nil {
		return err
	}
	if _, err := s.run(ctx, workspace, "remote", "add", "origin", repoPath); err != nil {
		return err
	}
	if _, err := s.run(ctx, workspace, "push", "-u", "origin", branch); err != nil {
		return err
	}
	if err := s.SetHEAD(ctx, repoPath, branch); err != nil {
		return errors.Join(errors.New("设置初始默认分支 HEAD 失败"), err)
	}
	return chmodRecursive(repoPath)
}
