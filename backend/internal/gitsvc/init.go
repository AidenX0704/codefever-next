// InitOptions 描述建仓时的可选初始化内容。
type InitOptions struct {
	// DefaultBranch 初始默认分支名（缺省 "main"）。
	DefaultBranch string
	// InitReadme 为真时自动生成 README.md。
	InitReadme bool
	// RepoDisplayName 用于生成 README 标题。
	RepoDisplayName string
	// RepoDescription 用于生成 README 正文。
	RepoDescription string
	// Gitignore 可选 .gitignore 模板名（见 GitignoreTemplate）。
	Gitignore string
	// AuthorName / AuthorEmail 初始提交的作者身份。
	AuthorName  string
	AuthorEmail string
}

